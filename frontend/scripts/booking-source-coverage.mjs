// Writes docs/booking-source-coverage.md: every public route of the website and what the booking-source resolver
// (src/utils/pageIdentity.js) makes of it. Deterministic, so a test can check the file is current.
//   node scripts/booking-source-coverage.mjs           write the report
//   node scripts/booking-source-coverage.mjs --check   exit 1 if the file on disk is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isNoindexPath, normalizePath } from "../src/seo/routes.js";
import { categories, specialties, conditions } from "../src/data/searchIndex.js";
import { resolvePage } from "../src/utils/pageIdentity.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const APP = path.join(here, "../src/App.jsx");
const OUT = path.join(here, "../../docs/booking-source-coverage.md");

export function buildReport() {
  // Routes inside comments (old, switched-off routes) are not routes.
  const source = fs
    .readFileSync(APP, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
  const all = [...new Set([...source.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1]))].sort();
  const staticPaths = all.filter((p) => p.startsWith("/") && !p.includes(":") && p !== "*");
  const isPublic = (p) => !isNoindexPath(normalizePath(p));
  const publicRoutes = staticPaths.filter(isPublic);
  const privateCount = staticPaths.length - publicRoutes.length;

  const rows = publicRoutes.map((p) => ({ route: p, ...resolvePage(p) }));
  const groups = { data: [], hand: [], seo: [], path: [], none: [] };
  for (const r of rows) groups[r.via].push(r);

  const esc = (s) => String(s).replace(/\|/g, "\|");
  const table = (list) =>
    list.length
      ? ["| Route | Type | Name |", "| --- | --- | --- |", ...list.map((r) => `| \`${esc(r.route)}\` | ${r.type} | ${esc(r.name) || "—"} |`)].join("\n")
      : "_None._";

  const indexRoutes = new Set([...categories, ...specialties, ...conditions].map((e) => normalizePath(e.route)));
  const appPaths = new Set(staticPaths.map(normalizePath));
  const staleIndex = [...indexRoutes].filter((r) => !appPaths.has(r)).sort();

  const dynamic = [
    ["/appointment-booking/mental-health", undefined],
    ["/appointment-booking/mental-health/psychiatry", undefined],
    ["/appointment-booking/mental-health/psychiatry/anxiety", undefined],
    ["/appointment-booking/not-a-real-category", undefined],
    ["/doctors/martin-perlin", { doctorName: "Martin Perlin" }],
    ["/doctors/martin-perlin", undefined],
    ["/doctor/64b0000000000000000000d1", undefined],
    ["/travelling-with-asthma", { blogTitle: "Travelling with asthma | Humancare Connect" }],
    ["/travelling-with-asthma", undefined],
    ["/doctors-note", undefined],
    ["/user/dashboard", undefined],
    ["/pay/abc123def456ghi789jkl012", undefined],
    ["/login", undefined],
  ];
  const dynamicRows = dynamic.map(([p, hints]) => {
    const r = resolvePage(p, hints);
    return `| \`${esc(p)}\` | ${hints ? "`" + esc(JSON.stringify(hints)) + "`" : "—"} | ${r.type} | ${esc(r.name) || "—"} | ${r.via} |`;
  });

  const lines = [
    "# Booking source: page coverage",
    "",
    "Generated by `frontend/scripts/booking-source-coverage.mjs` from `src/App.jsx` and `src/utils/pageIdentity.js`. Do not edit by hand; run `npm run report:booking-source` in `frontend/`.",
    "",
    "Every public route (no params, not noindex/private) and what the resolver names it. `via` says how: **data** = matched in `src/data/searchIndex.js`, **hand** = the hand table or a structural rule in `pageIdentity.js`, **seo** = the page title in `src/seo/routes.js`, **path** = prettified from the URL (the least reliable), **none** = private, never named.",
    "",
    "## Summary",
    "",
    "| How the name is found | Routes |",
    "| --- | --- |",
    `| data (searchIndex) | ${groups.data.length} |`,
    `| hand table / structure | ${groups.hand.length} |`,
    `| SEO title | ${groups.seo.length} |`,
    `| path only (fallback) | ${groups.path.length} |`,
    `| private (never named) | ${groups.none.length} |`,
    `| **Public routes** | **${rows.length}** |`,
    "",
    `Not counted: ${privateCount} private/noindex routes (dashboards, login, payment, booking steps) and ${all.length - staticPaths.length} routes with params (below).`,
    "",
    "By type: " +
      Object.entries(rows.reduce((acc, r) => ((acc[r.type] = (acc[r.type] || 0) + 1), acc), {}))
        .sort((a, b) => b[1] - a[1])
        .map(([t, n]) => `${t} ${n}`)
        .join(", ") +
      ".",
    "",
    "## Fall back to the path (review these)",
    "",
    table(groups.path),
    "",
    "## Named from the SEO title (type unknown unless a blog)",
    "",
    table(groups.seo),
    "",
    "## Hand table and structural rules",
    "",
    table(groups.hand),
    "",
    "## Matched in searchIndex data",
    "",
    table(groups.data),
    "",
    "## Routes with params and private pages",
    "",
    "| Route | Hints | Type | Name | Via |",
    "| --- | --- | --- | --- | --- |",
    ...dynamicRows,
    "",
    "## searchIndex routes that do not exist in App.jsx",
    "",
    `${staleIndex.length} entries in \`src/data/searchIndex.js\` point at a route that App.jsx does not define (its own NOTES block lists known gaps). They never match a real page, so they are harmless here: ${staleIndex.length ? "`" + staleIndex.join("`, `") + "`" : "none"}.`,
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = buildReport();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current.replace(/\r\n/g, "\n") !== report) {
      console.error("docs/booking-source-coverage.md is out of date: run `npm run report:booking-source`");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, report);
    console.log("wrote", OUT);
  }
}
